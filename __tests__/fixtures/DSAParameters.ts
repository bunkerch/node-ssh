export function rfc6979Mpint(hex: string): Buffer {
    const unsigned = Buffer.from(hex.replace(/\s/g, ""), "hex")
    return (unsigned[0] & 0x80) === 0 ? unsigned : Buffer.concat([Buffer.from([0]), unsigned])
}

