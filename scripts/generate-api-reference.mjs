import { readFile, mkdir, writeFile } from "node:fs/promises"
import { dirname, relative, resolve, sep } from "node:path"
import { fileURLToPath } from "node:url"
import ts from "typescript"

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const outputDirectory = resolve(root, "docs/api")
const check = process.argv.includes("--check")
const generatedNotice = "<!-- Generated by scripts/generate-api-reference.mjs. Do not edit. -->"

const categories = [
    ["connections", "Connections and servers"],
    ["channels", "Channels and forwarding"],
    ["authentication", "Authentication"],
    ["agents", "Agents and public-key management"],
    ["sftp", "SFTP"],
    ["keys", "Keys, trust, and signatures"],
    ["transport", "Transport and protocol types"],
]

function categoryFor(path) {
    const normalized = path.split(sep).join("/")
    if (/\/sftp\//u.test(normalized)) return "sftp"
    if (
        /\/channels\//u.test(normalized) ||
        /\/(?:Channel|TerminalModes)\.d\.ts$/u.test(normalized)
    ) {
        return "channels"
    }
    if (/\/publickey\//u.test(normalized)) return "agents"
    if (/\/(?:GSSAPI|AgentForwarding)\.d\.ts$/u.test(normalized) || /\/auth\//u.test(normalized)) {
        return "authentication"
    }
    if (
        /\/(?:AllowedSigners|KeyGeneration|KeyParsing|KeyRevocationList|KnownHosts|SecurityKeyAttestation|SSHSignature)\.d\.ts$/u.test(
            normalized,
        ) ||
        /\/utils\/(?:PrivateKey|PublicKey|PuTTYPrivateKey|RFC4716|Signature)\.d\.ts$/u.test(
            normalized,
        )
    ) {
        return "keys"
    }
    if (
        /\/(?:Client|Server|ServerClient|HTTPAgents|ConnectionConfiguration)\.d\.ts$/u.test(
            normalized,
        )
    ) {
        return "connections"
    }
    return "transport"
}

function anchor(name) {
    return name
        .toLowerCase()
        .replace(/[^a-z0-9_ -]+/gu, "")
        .replace(/ +/gu, "-")
        .replace(/^-|-$/gu, "")
}

function declarationName(declaration) {
    if ("name" in declaration && declaration.name && ts.isIdentifier(declaration.name)) {
        return declaration.name.text
    }
    return undefined
}

function declarationRoot(declaration) {
    if (ts.isVariableDeclaration(declaration)) return declaration.parent.parent
    return declaration
}

function isPrivate(member) {
    return (
        ("name" in member && member.name && ts.isPrivateIdentifier(member.name)) ||
        (ts.getCombinedModifierFlags(member) &
            (ts.ModifierFlags.Private | ts.ModifierFlags.Protected)) !==
            0
    )
}

function printableDeclaration(declaration) {
    const rootDeclaration = declarationRoot(declaration)
    if (!ts.isClassDeclaration(rootDeclaration)) return rootDeclaration
    return ts.factory.updateClassDeclaration(
        rootDeclaration,
        rootDeclaration.modifiers,
        rootDeclaration.name,
        rootDeclaration.typeParameters,
        rootDeclaration.heritageClauses,
        rootDeclaration.members.filter((member) => !isPrivate(member)),
    )
}

function kindFor(symbol) {
    if (symbol.flags & ts.SymbolFlags.Class) return "Class"
    if (symbol.flags & ts.SymbolFlags.Interface) return "Interface"
    if (symbol.flags & ts.SymbolFlags.TypeAlias) return "Type"
    if (symbol.flags & ts.SymbolFlags.Function) return "Function"
    if (symbol.flags & ts.SymbolFlags.Enum) return "Enum"
    if (symbol.flags & ts.SymbolFlags.Variable) return "Constant"
    return "Declaration"
}

async function main() {
    const dist = resolve(root, "dist")
    const declarationFiles = ts.sys.readDirectory(dist, [".d.ts"])
    const program = ts.createProgram(declarationFiles, {
        module: ts.ModuleKind.NodeNext,
        moduleResolution: ts.ModuleResolutionKind.NodeNext,
        target: ts.ScriptTarget.ESNext,
        skipLibCheck: true,
    })
    const checker = program.getTypeChecker()
    const index = program.getSourceFile(resolve(dist, "index.d.ts"))
    if (!index) throw new Error("dist/index.d.ts is missing; run pnpm build first")
    const moduleSymbol = checker.getSymbolAtLocation(index)
    if (!moduleSymbol) throw new Error("Could not inspect the package entry point")

    const entries = checker
        .getExportsOfModule(moduleSymbol)
        .map((exported) => {
            const target =
                exported.flags & ts.SymbolFlags.Alias
                    ? checker.getAliasedSymbol(exported)
                    : exported
            const declarations = (target.getDeclarations() ?? [])
                .filter((declaration) => declaration.getSourceFile().fileName.startsWith(dist))
                .map(declarationRoot)
                .filter(
                    (declaration, index, all) =>
                        all.findIndex(
                            (candidate) =>
                                candidate.getSourceFile() === declaration.getSourceFile() &&
                                candidate.pos === declaration.pos &&
                                candidate.end === declaration.end,
                        ) === index,
                )
            if (declarations.length === 0) {
                throw new Error(`No package declaration found for ${exported.name}`)
            }
            const source = declarations[0].getSourceFile().fileName
            return {
                name: exported.name,
                target,
                declarations,
                declaredName: declarations.map(declarationName).find(Boolean),
                category: categoryFor(source),
                source,
                kind: kindFor(target),
            }
        })
        .sort((left, right) => left.name.localeCompare(right.name))

    const printer = ts.createPrinter({ newLine: ts.NewLineKind.LineFeed })
    const files = new Map()
    for (const [category, title] of categories) {
        const categoryEntries = entries.filter((entry) => entry.category === category)
        const sections = categoryEntries.map((entry) => {
            const sourceFile = entry.declarations[0].getSourceFile()
            const declarationText = entry.declarations
                .map((declaration) =>
                    printer.printNode(
                        ts.EmitHint.Unspecified,
                        printableDeclaration(declaration),
                        sourceFile,
                    ),
                )
                .join("\n")
            const sourcePath = relative(dist, entry.source)
                .split(sep)
                .join("/")
                .replace(/\.d\.ts$/u, ".ts")
            const alias =
                entry.declaredName && entry.declaredName !== entry.name
                    ? `\nPackage export alias of \`${entry.declaredName}\`.\n`
                    : ""
            return `## ${entry.name}\n\n${entry.kind}. Declared in [\`src/${sourcePath}\`](../../src/${sourcePath}).${alias}\n\n\`\`\`ts\n${declarationText.trim()}\n\`\`\``
        })
        files.set(
            `${category}.md`,
            `${generatedNotice}\n\n# ${title}\n\nExact declarations for ${categoryEntries.length} package-root exports. Private and protected class members are omitted.\n\n${sections.join("\n\n")}\n`,
        )
    }

    const categoryTitles = new Map(categories)
    const indexRows = entries
        .map(
            (entry) =>
                `| [\`${entry.name}\`](${entry.category}.md#${anchor(entry.name)}) | ${entry.kind} | ${categoryTitles.get(entry.category)} |`,
        )
        .join("\n")
    files.set(
        "README.md",
        `${generatedNotice}\n\n# API reference\n\nThis reference is generated from the declarations shipped by the package. It covers all ${entries.length} exports available from \`@bunkerch/modernssh\`. Class sections contain every public constructor, property, accessor, and method declared by that class; inherited Node.js stream and EventEmitter members remain documented by Node.js.\n\nRegenerate it with \`pnpm docs:api\`. CI runs \`pnpm docs:api:check\` to prevent the reference from drifting from \`dist/*.d.ts\`.\n\n| Export | Kind | Area |\n| --- | --- | --- |\n${indexRows}\n`,
    )

    await mkdir(outputDirectory, { recursive: true })
    for (const [name, contents] of files) {
        const path = resolve(outputDirectory, name)
        if (check) {
            let current
            try {
                current = await readFile(path, "utf8")
            } catch {
                throw new Error(`Generated API reference is missing ${relative(root, path)}`)
            }
            if (current !== contents) {
                throw new Error(`Generated API reference is stale: ${relative(root, path)}`)
            }
        } else {
            await writeFile(path, contents)
        }
    }
}

await main()
